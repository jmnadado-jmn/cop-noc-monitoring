function generate30DayHistory(
  baseUptime: number,
  outageDays: { dayOffset: number; downtimeMins: number }[] = []
): DailyUptimePoint[] {
  const points: DailyUptimePoint[] = [];
  const baseDate = new Date('2026-09-26T00:00:00-07:00');

  for (let i = 29; i >= 0; i--) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    const outage = outageDays.find((o) => o.dayOffset === i);
    if (outage) {
      const pct = Math.max(
        0,
        Number((((1440 - outage.downtimeMins) / 1440) * 100).toFixed(2))
      );
      points.push({
        date: dateStr,
        uptimePct: pct,
        downtimeMinutes: outage.downtimeMins,
        incidentCount: 1,
      });
    } else {
      const pct = Math.min(100, Number(baseUptime.toFixed(2)));
      const downMins = pct === 100 ? 0 : Math.round(((100 - pct) / 100) * 1440);
      points.push({
        date: dateStr,
        uptimePct: pct,
        downtimeMinutes: downMins,
        incidentCount: 0,
      });
    }
  }
  return points;
}

